import json
import uuid
from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field
from mcp.registry import mcp_registry
from backend.app.core.database import SessionLocal
from backend.app.models.document import Document


class GenerateSummaryReportParams(BaseModel):
    document_ids: List[str] = Field(..., min_length=1)
    report_title: Optional[str] = "Medical Intelligence Summary Report"


def generate_summary_report_tool(document_ids: List[str], report_title: str = "Medical Intelligence Summary Report", user_context: Optional[Dict[str, Any]] = None):
    db = SessionLocal()
    try:
        docs = db.query(Document).filter(Document.id.in_(document_ids)).all()
        if not docs:
            raise ValueError("No matching documents found for report generation.")

        doc_summaries = []
        for d in docs:
            doc_summaries.append({
                "document_id": d.id,
                "filename": d.filename,
                "title": d.title,
                "category": d.category or "General",
                "page_count": d.page_count,
                "summary": d.summary or "Summary not available."
            })

        markdown_report = (
            f"# {report_title}\n\n"
            f"**Generated by:** MedAssist AI Document Intelligence Platform\n"
            f"**Analyzed Documents Count:** {len(docs)}\n\n"
            "## Executive Overview\n\n"
            "This report consolidates findings, extracted parameters, and structural summaries across the designated healthcare documents.\n\n"
            "## Document Breakdown\n\n"
        )

        for s in doc_summaries:
            markdown_report += (
                f"### {s['title']} ({s['filename']})\n"
                f"- **Category:** `{s['category']}`\n"
                f"- **Pages:** {s['page_count']}\n"
                f"- **Core Finding:** {s['summary']}\n\n"
            )

        markdown_report += (
            "---\n"
            "*Educational Notice: MedAssist AI generated synthesis. Not a diagnostic report.*"
        )

        report_id = str(uuid.uuid4())
        return {
            "report_id": report_id,
            "title": report_title,
            "document_count": len(docs),
            "markdown_content": markdown_report,
            "summary_data": doc_summaries
        }
    finally:
        db.close()


class ExportReportParams(BaseModel):
    report_title: str
    markdown_content: str
    export_format: str = Field("markdown", pattern="^(markdown|json|text)$")


def export_report_tool(report_title: str, markdown_content: str, export_format: str = "markdown", user_context: Optional[Dict[str, Any]] = None):
    if export_format == "json":
        export_payload = json.dumps({
            "title": report_title,
            "content": markdown_content,
            "format": "json"
        }, indent=2)
        mime = "application/json"
    else:
        export_payload = markdown_content
        mime = "text/markdown"

    return {
        "title": report_title,
        "format": export_format,
        "mime_type": mime,
        "payload": export_payload
    }


def register_reporting_server_tools():
    mcp_registry.register_tool(
        name="generate_summary_report",
        server="reporting_server",
        description="Generates a structured medical synthesis and comparison report across documents.",
        func=generate_summary_report_tool,
        param_model=GenerateSummaryReportParams,
        read_only=True
    )
    mcp_registry.register_tool(
        name="export_report",
        server="reporting_server",
        description="Exports medical intelligence reports into Markdown, JSON, or plain text format.",
        func=export_report_tool,
        param_model=ExportReportParams,
        read_only=True
    )


register_reporting_server_tools()
